"""recorder — the append-only in-run sink that pipeline stages write provenance into.

:class:`ProvenanceRecorder` (provenance-core design, "Emission Layer →
ProvenanceRecorder") accepts source, evidence, claim, derivation and
validation records, validation findings and per-stage complete / failed marks
without the emitting stage knowing how the records are later assembled (1.2).
:meth:`ProvenanceRecorder.snapshot` hands everything accepted so far to the
assembly layer as an immutable :class:`~provenance.models.RecordedRun`.

Semantics
---------
Append-only
    The public surface is ``record_*``, ``issue_sink``, ``mark_stage_*`` and
    ``snapshot``; nothing updates or deletes a record, and a previously
    recorded record is never removed.
Duplicate identity
    Recording the same identifier twice with identical content is a no-op
    (idempotent retry safety). Recording it with differing content keeps the
    first record and appends a ``duplicate_identity`` finding naming the
    identifier. Node IDs, edge IDs and caller-supplied finding IDs follow this
    rule; a finding generated by the recorder itself is de-duplicated on its
    content, so a retried issue or conflict is recorded once.
Issue sink
    :meth:`ProvenanceRecorder.issue_sink` returns a ``(code, message,
    details)`` callable for ``pipeline.validator``: each call records one
    :class:`~provenance.models.ValidationFinding` whose severity is the
    default for ``code`` and whose ``node_id`` / ``edge_id`` are taken from
    ``details["node_id"]`` / ``details["edge_id"]`` when present, so a bad
    ``loc`` reference becomes a recorded issue while the claim is retained
    (5.4).
Stages
    Every stage in ``STAGE_ORDER`` reads ``not_run`` until marked, so a stage
    that emitted nothing stays visible against its contract (1.6, 2.1). Status
    only escalates (``not_run`` → ``complete`` → ``failed``): a failure is
    never erased by a later completion. A mark is run-wide by default
    (``source_id=None``: ``stage_status`` / ``stage_failure_reasons``, first
    failure reason kept) — used for ``chain_validation`` and for failures
    before any document is known. With a ``source_id`` it applies to that one
    document only (``document_stage_status`` /
    ``document_stage_failure_reasons``) and leaves the run-wide status
    unchanged; per document and stage every distinct failure reason is kept,
    in recording order (2.5). A malformed ``source_id`` raises
    :class:`~provenance.identity.InvalidIdentifierError`. Only
    ``DerivationStep`` carries a ``stage``, so ``record_derivation`` and the
    ``mark_stage_*`` methods reject an undeclared stage with
    :class:`~provenance.contracts.UnknownStageError` — in both modes, so
    contract drift is caught whether provenance is on or off.
Disabled mode
    ``enabled=False`` makes every method store nothing while still returning
    the record identifiers, so the pipeline never branches on provenance being
    off; input checks still apply.
Concurrency
    PDF-level tasks record concurrently. All mutation happens under a single
    ``threading.Lock`` held only around dictionary updates, and
    :meth:`snapshot` copies under that same lock. Records are frozen values, so
    none is ever partially visible.

The recorder performs no file or network access (1.5) and is constructed once
per run and passed explicitly — there is no module-level instance.

Imports only the standard library, ``provenance.models``,
``provenance.contracts``, ``provenance.identity`` and ``utils.logging_utils``.
"""

from __future__ import annotations

import dataclasses
import threading
from collections.abc import Callable, Mapping, Sequence
from typing import Any, Literal

from provenance.contracts import STAGE_ORDER, require_declared_stage
from provenance.identity import SOURCE_ID_PREFIX, InvalidIdentifierError, derive_source_id
from provenance.models import (
    DEFAULT_SEVERITIES,
    ClaimNode,
    DerivationStep,
    EvidenceNode,
    ProvenanceEdge,
    ProvenanceNode,
    RecordedRun,
    RunIdentity,
    SourceNode,
    ValidationFinding,
    ValidationRecord,
)
from utils.logging_utils import get_logger

__all__ = ["ProvenanceRecorder", "IssueSink"]

logger = get_logger(__name__)

IssueSink = Callable[[str, str, Mapping[str, Any]], None]
"""``(code, message, details) -> None``: the callable handed to the chunk validator."""

StageStatus = Literal["complete", "failed", "not_run"]

_DUPLICATE_IDENTITY = "duplicate_identity"
_FINDING_ID_PREFIX = "finding:"
_RUN_SUBJECT = "run"
_STATUS_RANK: Mapping[str, int] = {"not_run": 0, "complete": 1, "failed": 2}
_ABSENT = object()


def _require_instance(value: object, expected: type, what: str) -> None:
    if not isinstance(value, expected):
        raise TypeError(f"{what} must be a {expected.__name__}, got {type(value).__name__}")


def _require_sequence(value: object, what: str) -> tuple[Any, ...]:
    # A bare string is a Sequence of characters; reject it explicitly.
    if isinstance(value, (str, bytes)) or not isinstance(value, Sequence):
        raise TypeError(f"{what} must be a sequence, got {type(value).__name__}")
    return tuple(value)


def _differing_fields(first: object, second: object) -> list[str]:
    """Names of dataclass fields whose values differ (or exist on only one side)."""
    a = {f.name: getattr(first, f.name) for f in dataclasses.fields(first)}  # type: ignore[arg-type]
    b = {f.name: getattr(second, f.name) for f in dataclasses.fields(second)}  # type: ignore[arg-type]
    return sorted(name for name in a.keys() | b.keys() if a.get(name, _ABSENT) != b.get(name, _ABSENT))


def _finding_key(finding: ValidationFinding) -> tuple[Any, ...] | None:
    """Content key of a recorder-generated finding, or ``None`` when unhashable."""
    key = (finding.code, finding.severity, finding.node_id, finding.edge_id, finding.message, finding.details)
    try:
        hash(key)
    except TypeError:
        return None
    return key


def _check_source_id(source_id: object) -> str | None:
    """Return ``source_id`` when it is ``None`` or a well-formed ``src:<fingerprint>``, else raise."""
    if source_id is None:
        return None
    if not isinstance(source_id, str) or not source_id.startswith(SOURCE_ID_PREFIX):
        raise InvalidIdentifierError(f"source_id must be {SOURCE_ID_PREFIX!r} plus a fingerprint, got {source_id!r}")
    try:
        # derive_source_id validates the fingerprint (non-empty, no '#', no whitespace).
        derive_source_id(source_id[len(SOURCE_ID_PREFIX) :])
    except InvalidIdentifierError as exc:
        raise InvalidIdentifierError(f"malformed source_id {source_id!r}: {exc}") from exc
    return source_id


def _optional_id(details: Mapping[str, Any], key: str) -> str | None:
    value = details.get(key)
    return value if isinstance(value, str) and value else None


class ProvenanceRecorder:
    """Append-only, thread-safe sink of one run's provenance records."""

    def __init__(self, run: RunIdentity, *, enabled: bool = True) -> None:
        _require_instance(run, RunIdentity, "run")
        if not isinstance(enabled, bool):
            raise TypeError(f"enabled must be a bool, got {type(enabled).__name__}")
        self._run = run
        self._enabled = enabled
        self._lock = threading.Lock()
        self._nodes: dict[str, ProvenanceNode] = {}
        self._edges: dict[str, ProvenanceEdge] = {}
        self._findings: dict[str, ValidationFinding] = {}
        self._generated_keys: dict[tuple[Any, ...], str] = {}
        self._finding_ordinals: dict[tuple[str, str], int] = {}
        self._stage_status: dict[str, StageStatus] = {}
        self._stage_failure_reasons: dict[str, str] = {}
        self._document_stage_status: dict[str, dict[str, StageStatus]] = {}
        self._document_stage_failure_reasons: dict[str, dict[str, list[str]]] = {}

    # ------------------------------------------------------------------
    # Record methods
    # ------------------------------------------------------------------

    def record_source(self, node: SourceNode) -> str:
        """Record one source document; return its node ID."""
        _require_instance(node, SourceNode, "node")
        return self._record_nodes((node,))[0]

    def record_evidence(self, nodes: Sequence[EvidenceNode]) -> tuple[str, ...]:
        """Record evidence nodes; return their node IDs in input order."""
        batch = _require_sequence(nodes, "nodes")
        for node in batch:
            _require_instance(node, EvidenceNode, "each evidence node")
        return self._record_nodes(batch)

    def record_claim(self, node: ClaimNode, edges: Sequence[ProvenanceEdge]) -> str:
        """Record one claim and its edges (e.g. ``cites_evidence``); return the claim ID."""
        _require_instance(node, ClaimNode, "node")
        edge_batch = _require_sequence(edges, "edges")
        for edge in edge_batch:
            _require_instance(edge, ProvenanceEdge, "each edge")
        return self._record_nodes((node,), edge_batch)[0]

    def record_derivation(self, step: DerivationStep) -> str:
        """Record one derivation step against a declared stage; return its node ID."""
        _require_instance(step, DerivationStep, "step")
        require_declared_stage(step.stage)
        return self._record_nodes((step,))[0]

    def record_validation(self, record: ValidationRecord) -> str:
        """Record one validation record; return its node ID."""
        _require_instance(record, ValidationRecord, "record")
        return self._record_nodes((record,))[0]

    def record_issue(self, finding: ValidationFinding) -> None:
        """Record a caller-built finding, keyed by its ``finding_id``."""
        _require_instance(finding, ValidationFinding, "finding")
        if not self._enabled:
            return
        new: list[ValidationFinding] = []
        with self._lock:
            existing = self._findings.get(finding.finding_id)
            if existing is None:
                self._findings[finding.finding_id] = finding
                new.append(finding)
            elif existing != finding:
                conflict = self._duplicate_identity(
                    "finding",
                    finding.finding_id,
                    existing,
                    finding,
                    extra={"finding_id": finding.finding_id},
                )
                generated = self._append_generated_locked(conflict, subject=finding.finding_id)
                if generated is not None:
                    new.append(generated)
        self._log_findings(new)

    def issue_sink(self) -> IssueSink:
        """Return the ``(code, message, details)`` callable for ``pipeline.validator`` (5.4)."""
        return self._accept_issue

    # ------------------------------------------------------------------
    # Stage marks
    # ------------------------------------------------------------------

    def mark_stage_complete(self, stage: str, *, source_id: str | None = None) -> None:
        """Mark a declared stage complete, run-wide or for one document; never overrides a failure."""
        require_declared_stage(stage)
        source_id = _check_source_id(source_id)
        if not self._enabled:
            return
        with self._lock:
            self._escalate_locked(stage, "complete", source_id)

    def mark_stage_failed(self, stage: str, reason: str, *, source_id: str | None = None) -> None:
        """Mark a declared stage failed, run-wide (first reason kept) or for one document (every reason kept)."""
        require_declared_stage(stage)
        if not isinstance(reason, str):
            raise TypeError(f"reason must be a str, got {type(reason).__name__}")
        source_id = _check_source_id(source_id)
        if not self._enabled:
            return
        with self._lock:
            self._escalate_locked(stage, "failed", source_id)
            if source_id is None:
                self._stage_failure_reasons.setdefault(stage, reason)
                return
            reasons = self._document_stage_failure_reasons.setdefault(source_id, {}).setdefault(stage, [])
            if reason not in reasons:
                reasons.append(reason)

    # ------------------------------------------------------------------
    # Snapshot
    # ------------------------------------------------------------------

    def snapshot(self) -> RecordedRun:
        """Return an immutable copy of everything recorded so far; equal across repeated calls."""
        with self._lock:
            nodes = dict(self._nodes)
            edges = tuple(self._edges.values())
            findings = tuple(self._findings.values())
            stage_status = {stage: self._stage_status.get(stage, "not_run") for stage in STAGE_ORDER}
            reasons = dict(self._stage_failure_reasons)
            # Documents in source-id order and stages in declared order, so equal marks
            # give equal snapshots whatever order concurrent tasks marked them in.
            document_status = {
                source_id: {stage: by_stage[stage] for stage in STAGE_ORDER if stage in by_stage}
                for source_id, by_stage in sorted(self._document_stage_status.items())
            }
            document_reasons = {
                source_id: {stage: tuple(by_stage[stage]) for stage in STAGE_ORDER if stage in by_stage}
                for source_id, by_stage in sorted(self._document_stage_failure_reasons.items())
            }
        return RecordedRun(
            run=self._run,
            nodes=nodes,
            edges=edges,
            findings=findings,
            stage_status=stage_status,
            stage_failure_reasons=reasons,
            document_stage_status=document_status,
            document_stage_failure_reasons=document_reasons,
        )

    # ------------------------------------------------------------------
    # Internals
    # ------------------------------------------------------------------

    def _record_nodes(
        self,
        nodes: tuple[ProvenanceNode, ...],
        edges: tuple[ProvenanceEdge, ...] = (),
    ) -> tuple[str, ...]:
        ids = tuple(node.node_id for node in nodes)
        if not self._enabled:
            return ids
        new: list[ValidationFinding] = []
        with self._lock:
            for node in nodes:
                existing = self._nodes.get(node.node_id)
                if existing is None:
                    self._nodes[node.node_id] = node
                elif existing != node:
                    conflict = self._duplicate_identity(
                        "node",
                        node.node_id,
                        existing,
                        node,
                        node_id=node.node_id,
                        extra={"kept_kind": existing.kind, "rejected_kind": node.kind},
                    )
                    generated = self._append_generated_locked(conflict, subject=node.node_id)
                    if generated is not None:
                        new.append(generated)
            for edge in edges:
                existing_edge = self._edges.get(edge.edge_id)
                if existing_edge is None:
                    self._edges[edge.edge_id] = edge
                elif existing_edge != edge:
                    conflict = self._duplicate_identity(
                        "edge", edge.edge_id, existing_edge, edge, edge_id=edge.edge_id
                    )
                    generated = self._append_generated_locked(conflict, subject=edge.edge_id)
                    if generated is not None:
                        new.append(generated)
        self._log_findings(new)
        return ids

    def _accept_issue(self, code: str, message: str, details: Mapping[str, Any]) -> None:
        if not isinstance(code, str):
            raise TypeError(f"code must be a str, got {type(code).__name__}")
        if code not in DEFAULT_SEVERITIES:
            raise ValueError(f"unknown finding code {code!r}; known codes: {sorted(DEFAULT_SEVERITIES)}")
        if not isinstance(message, str):
            raise TypeError(f"message must be a str, got {type(message).__name__}")
        if not isinstance(details, Mapping):
            raise TypeError(f"details must be a mapping, got {type(details).__name__}")
        if not self._enabled:
            return
        node_id = _optional_id(details, "node_id")
        edge_id = _optional_id(details, "edge_id")
        # Built outside the lock: construction freezes (copies) ``details``.
        finding = ValidationFinding(
            finding_id="",
            code=code,
            severity=DEFAULT_SEVERITIES[code],
            node_id=node_id,
            edge_id=edge_id,
            message=message,
            details=details,
        )
        with self._lock:
            generated = self._append_generated_locked(finding, subject=node_id or edge_id or _RUN_SUBJECT)
        self._log_findings([generated] if generated is not None else [])

    @staticmethod
    def _duplicate_identity(
        record_kind: str,
        identifier: str,
        first: object,
        second: object,
        *,
        node_id: str | None = None,
        edge_id: str | None = None,
        extra: Mapping[str, Any] | None = None,
    ) -> ValidationFinding:
        details: dict[str, Any] = {"record_kind": record_kind, **(extra or {})}
        details["differing_fields"] = _differing_fields(first, second)
        return ValidationFinding(
            finding_id="",
            code=_DUPLICATE_IDENTITY,
            severity=DEFAULT_SEVERITIES[_DUPLICATE_IDENTITY],
            node_id=node_id,
            edge_id=edge_id,
            message=(
                f"{record_kind} {identifier!r} recorded twice with differing content; first record kept"
            ),
            details=details,
        )

    def _append_generated_locked(self, finding: ValidationFinding, *, subject: str) -> ValidationFinding | None:
        """Assign an ID to a recorder-generated finding and append it, unless already recorded.

        Caller must hold ``self._lock``.
        """
        key = _finding_key(finding)
        if key is not None and key in self._generated_keys:
            return None
        ordinal_key = (finding.code, subject)
        ordinal = self._finding_ordinals.get(ordinal_key, 0)
        while True:
            ordinal += 1
            finding_id = f"{_FINDING_ID_PREFIX}{finding.code}:{subject}:{ordinal}"
            if finding_id not in self._findings:
                break
        self._finding_ordinals[ordinal_key] = ordinal
        recorded = dataclasses.replace(finding, finding_id=finding_id)
        self._findings[finding_id] = recorded
        if key is not None:
            self._generated_keys[key] = finding_id
        return recorded

    def _escalate_locked(self, stage: str, status: StageStatus, source_id: str | None) -> None:
        """Raise the run-wide (``source_id=None``) or per-document status; caller holds the lock."""
        target = (
            self._stage_status
            if source_id is None
            else self._document_stage_status.setdefault(source_id, {})
        )
        current = target.get(stage, "not_run")
        if _STATUS_RANK[status] > _STATUS_RANK[current]:
            target[stage] = status

    @staticmethod
    def _log_findings(findings: Sequence[ValidationFinding]) -> None:
        for finding in findings:
            logger.debug(
                "provenance finding %s [%s] %s: %s",
                finding.finding_id,
                finding.severity,
                finding.code,
                finding.message,
            )
